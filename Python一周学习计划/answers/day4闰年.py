# Day 4 练习 2 参考答案：判断闰年
# 规则：能被 4 整除但不能被 100 整除，或者能被 400 整除

year = int(input("请输入年份："))

# % 是取余数：year % 4 == 0 表示"能被 4 整除"
# and 要求两边同时成立；or 只要一边成立即可
# 注意判断相等要用两个等号 ==
if (year % 4 == 0 and year % 100 != 0) or year % 400 == 0:
    print(f"{year}年是闰年")
else:
    print(f"{year}年不是闰年")

# 可以拿这几个年份验证：2000（是）、2024（是）、1900（不是）
