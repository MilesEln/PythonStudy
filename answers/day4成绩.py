# Day 4 练习 1 参考答案：成绩等级
# 要求：输入分数（0~100），90及以上优秀，80~89良好，60~79及格，60以下不及格

score = float(input("请输入分数："))

# elif 会从上往下依次判断，遇到第一个成立的条件就执行，后面的分支直接跳过
# 所以条件要按分数从高到低的顺序写
if score >= 90:
    print("优秀")
elif score >= 80:      # 能走到这里，说明 score 一定小于 90
    print("良好")
elif score >= 60:
    print("及格")
else:                  # 以上都不成立（即 60 分以下）时执行
    print("不及格")
